export type DatabaseSslCa = 'system' | 'supabase';

// Parameter TLS di URL yang dibaca pg-connection-string. Parameter ini menimpa opsi `ssl` yang diberikan lewat
// kode, jadi harus dibuang saat CA dipasang dari sini.
const URL_TLS_PARAMS = ['sslmode', 'sslrootcert', 'sslcert', 'sslkey', 'uselibpqcompat'];

/**
 * Opsi koneksi pg untuk Prisma. `system` memakai URL apa adanya (lokal: tanpa TLS; produksi lain: CA publik).
 * `supabase` memaksa TLS dengan verifikasi penuh (rantai ke root CA Supabase dan nama host), bukan mematikan
 * verifikasi seperti `sslmode=no-verify`.
 */
export function buildPgPoolConfig(databaseUrl: string, sslCa: DatabaseSslCa = 'system'): PoolConfig {
  if (sslCa === 'system') return { connectionString: databaseUrl };

  const url = new URL(databaseUrl);
  for (const param of URL_TLS_PARAMS) url.searchParams.delete(param);
  return {
    connectionString: url.toString(),
    ssl: { ca: SUPABASE_ROOT_CA_2021, rejectUnauthorized: true },
  };
}
